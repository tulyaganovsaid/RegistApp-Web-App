export function translateCountry(countryName: string, targetLang: LanguageCode): string {
  if (!countryName) return countryName;

  // 1. Check if the name matches a key in COUNTRY_TRANSLATIONS
  if (COUNTRY_TRANSLATIONS[countryName]) {
    return COUNTRY_TRANSLATIONS[countryName][targetLang] || countryName;
  }

  // 2. Otherwise search all entries in COUNTRY_TRANSLATIONS to see if name matches any of the values in ANY language
  const lowerName = countryName.toLowerCase();
  for (const key of Object.keys(COUNTRY_TRANSLATIONS)) {
    const record = COUNTRY_TRANSLATIONS[key];
    if (
      record.en.toLowerCase() === lowerName ||
      record.ru.toLowerCase() === lowerName ||
      record.fr.toLowerCase() === lowerName
    ) {
      return record[targetLang] || countryName;
    }
  }

  return countryName; // Fallback to original value
}

